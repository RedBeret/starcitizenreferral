const {chromium}=require(process.env.SC_PLAYWRIGHT_MODULE||'playwright');
const assert=require('assert/strict');
const fs=require('fs');
const os=require('os');
const path=require('path');
const base=process.env.SC_GUIDES_BASE||'http://127.0.0.1:4173';
const output=fs.mkdtempSync(path.join(os.tmpdir(),'sc-evergreen-check-'));
(async()=>{
    const browser=await chromium.launch({headless:true});
    const context=await browser.newContext({reducedMotion:'reduce'});
    const page=await context.newPage();
    const errors=[];
    page.on('pageerror',e=>errors.push(e.message));
    await page.setViewportSize({width:390,height:844});
    await page.goto(base+'/pages/guides/flight-checklist.html');
    const boxes=page.getByRole('checkbox');
    assert.equal(await boxes.count(),12);
    await page.getByRole('checkbox',{name:'I know the destination and what I intend to do there.'}).focus();
    await page.keyboard.press('Space');
    await page.waitForFunction(()=>document.querySelector('[data-checklist-progress]').textContent.startsWith('1 of 12'));
    for(let i=0;i<12;i++) await boxes.nth(i).check();
    await page.waitForFunction(()=>document.querySelector('[data-checklist-progress]').textContent==='12 of 12 items checked — review complete');
    await boxes.nth(3).uncheck();
    assert.match(await page.locator('[data-checklist-progress]').innerText(),/^11 of 12/);
    await page.getByRole('button',{name:'Reset checklist'}).click();
    await page.waitForFunction(()=>document.querySelector('[data-checklist-progress]').textContent==='0 of 12 items checked');
    assert.equal(await page.locator('input:checked').count(),0);
    await boxes.first().check();
    await page.reload();
    assert.equal(await page.locator('input:checked').count(),0);
    await page.evaluate(()=>{window.print=()=>window.__printRequested=true});
    await page.getByRole('button',{name:'Print checklist'}).click();
    assert.equal(await page.evaluate(()=>window.__printRequested),true);
    await page.locator('body').click({position:{x:2,y:2}});
    await page.evaluate(()=>{document.activeElement.blur();window.scrollTo(0,0)});
    await page.screenshot({path:output+'/checklist-mobile.png',fullPage:true});
    await page.emulateMedia({media:'print'});
    assert.equal(await page.locator('.site-head').isVisible(),false);
    assert.equal(await page.locator('.checklist-page').evaluate(e=>getComputedStyle(e).colorScheme),'light');
    assert.equal(await page.locator('.article-side').isVisible(),false);
    assert.equal(await page.locator('.checklist-controls').isVisible(),false);
    assert.equal(await page.getByRole('checkbox').count(),12);
    for(let i=0;i<12;i++) assert.ok(await boxes.nth(i).isVisible());
    await page.setViewportSize({width:794,height:1123});
    await page.screenshot({path:output+'/checklist-print.png',fullPage:true});
    await page.pdf({path:output+'/departure-checklist.pdf',format:'A4',margin:{top:'12mm',bottom:'12mm',left:'12mm',right:'12mm'},printBackground:false});
    await page.emulateMedia({media:'screen'});
    await page.setViewportSize({width:390,height:844});
    await page.goto(base+'/pages/guides/glossary.html#asop');
    assert.equal(await page.locator('#asop').innerText(),'ASOP terminal');
    assert.equal(await page.locator('.guide-glossary dt').count(),21);
    await page.screenshot({path:output+'/glossary-mobile.png',fullPage:true});
    // Core tasks remain usable without the enhancement script.
    const plain=await browser.newContext({javaScriptEnabled:false});
    const fallback=await plain.newPage();
    await fallback.goto(base+'/pages/guides/flight-checklist.html');
    await fallback.getByRole('checkbox').first().check();
    assert.equal(await fallback.locator('input:checked').count(),1);
    await fallback.getByRole('button',{name:'Reset checklist'}).click();
    assert.equal(await fallback.locator('input:checked').count(),0);
    assert.equal(await fallback.getByRole('button',{name:'Print checklist'}).count(),0);
    assert.equal(await fallback.locator('[data-checklist-progress]').isVisible(),false);
    await plain.close();
    assert.deepEqual(errors,[]);
    console.log(JSON.stringify({output,checks:['keyboard ticks','complete and incomplete counts','native reset','reload clears ticks','print action','print visibility','21 glossary terms','no-JavaScript checklist'],errors:0},null,2));
    await browser.close();
})().catch(error=>{console.error(error);process.exit(1)});
