const {chromium}=require(process.env.SC_PLAYWRIGHT_MODULE||'playwright');
const assert=require('assert/strict');
const fs=require('fs');
const path=require('path');
const os=require('os');
const root=path.resolve(__dirname,'..');
const catalog=JSON.parse(fs.readFileSync(root+'/_content/guides/catalog.json','utf8'));
const base=process.env.SC_GUIDES_BASE||'http://127.0.0.1:4173';
const output=fs.mkdtempSync(path.join(os.tmpdir(),'sc-discovery-check-'));
(async()=>{
    const browser=await chromium.launch({headless:true});
    const context=await browser.newContext({reducedMotion:'reduce'});
    const page=await context.newPage();
    const errors=[];
    page.on('pageerror',error=>errors.push(error.message));
    const hub=base+'/pages/guides/guide-library.html';
    await page.setViewportSize({width:390,height:844});
    await page.goto(hub);
    const query=page.getByRole('searchbox',{name:'Search guides'});
    const topic=page.getByLabel('Topic',{exact:true});
    const visible=page.locator('.library-card:visible');
    assert.equal(await visible.count(),catalog.length);
    await query.fill('  HÓTAS  ');
    assert.equal(await visible.count(),1);
    assert.match(await visible.first().getAttribute('href'),/keybindings/);
    await query.press('Enter');
    assert.equal(page.url(),hub,'Search must not submit text into the URL');
    await query.fill('AC');
    assert.equal(await visible.count(),1);
    assert.match(await visible.first().getAttribute('href'),/arena-commander-practice/);
    await query.fill('F4');
    assert.equal(await visible.count(),1);
    assert.match(await visible.first().getAttribute('href'),/essential-ship-controls/);
    await query.fill('Galaxy doors');
    assert.equal(await visible.count(),1);
    assert.match(await visible.first().getAttribute('href'),/essential-ship-controls/);
    await topic.selectOption('Ships & services');
    assert.equal(await visible.count(),0);
    assert.ok(await page.locator('[data-guide-empty]').isVisible());
    assert.equal(await page.locator('[data-guide-category]:visible').count(),0);
    await page.getByRole('button',{name:'Clear filters'}).click();
    await page.waitForFunction(total=>document.querySelector('[data-guide-count]').textContent===`${total} of ${total} guides shown`,catalog.length);
    assert.equal(await visible.count(),catalog.length);
    assert.equal(await query.inputValue(),'');
    assert.equal(await topic.inputValue(),'');
    await topic.selectOption('Core concepts');
    assert.equal(await visible.count(),catalog.filter(e=>e.group==='Core concepts').length);
    assert.equal(await page.locator('[data-guide-category]:visible').count(),1);
    await query.fill('<img src=x onerror=window.__injected=true>');
    assert.equal(await visible.count(),0);
    assert.equal(await page.evaluate(()=>window.__injected),undefined);
    await page.getByRole('button',{name:'Clear filters'}).click();
    await page.waitForFunction(()=>document.querySelector('[name="guide-category"]').value==='');
    await query.fill('cargo');
    await page.evaluate(()=>{document.activeElement.blur();window.scrollTo(0,0)});
    await page.screenshot({path:output+'/search-mobile.png',fullPage:true});
    await page.goto(base+'/pages/guides/mission-budget.html');
    const form=page.getByRole('form',{name:'Mission budget calculator'});
    const results=page.locator('[data-budget-results]');
    await page.getByRole('button',{name:'Calculate estimate'}).click();
    assert.equal(await results.isVisible(),false);
    assert.match(await page.locator('[data-budget-error]').innerText(),/Complete every field/);
    await page.getByRole('button',{name:'Load example'}).click();
    assert.equal(await page.locator('[data-budget-share]').innerText(),'15,000 aUEC');
    assert.equal(await page.locator('[data-budget-net]').innerText(),'12,000 aUEC');
    assert.equal(await page.locator('[data-budget-rate]').innerText(),'16,000 aUEC / hour');
    await page.getByLabel('Your trip costs (aUEC)').fill('20000');
    assert.equal(await results.isVisible(),false,'Changed inputs must hide a stale result');
    await page.getByRole('button',{name:'Calculate estimate'}).click();
    assert.equal(await page.locator('[data-budget-net]').innerText(),'-5,000 aUEC');
    assert.match(await page.locator('[data-budget-note]').innerText(),/costs exceed your share/);
    for(const [label,value] of [['Participants sharing the reward','0'],['Participants sharing the reward','2.5'],['Whole trip time (minutes)','0'],['Your trip costs (aUEC)','-1']]){
        await page.getByRole('button',{name:'Load example'}).click();
        await page.getByLabel(label,{exact:true}).fill(value);
        await page.getByRole('button',{name:'Calculate estimate'}).click();
        assert.equal(await results.isVisible(),false,label+' '+value);
        assert.match(await page.locator('[data-budget-error]').innerText(),/allowed whole-number range/);
    }
    await page.getByRole('button',{name:'Load example'}).click();
    await page.getByRole('button',{name:'Clear',exact:true}).click();
    assert.equal(await results.isVisible(),false);
    assert.equal(await page.getByLabel('Total contract reward (aUEC)').inputValue(),'');
    assert.equal(await page.getByLabel('Participants sharing the reward').inputValue(),'1');
    assert.equal(await page.getByLabel('Your trip costs (aUEC)').inputValue(),'0');
    assert.equal(await page.getByLabel('Whole trip time (minutes)').inputValue(),'');
    for(const width of [320,390,768,1440]){
        await page.setViewportSize({width,height:950});
        await page.getByRole('button',{name:'Load example'}).click();
        assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`Budget result overflows at ${width}`);
        if([390,1440].includes(width)){
            await page.evaluate(()=>{document.activeElement.blur();window.scrollTo(0,0)});
            await page.screenshot({path:`${output}/budget-${width}.png`,fullPage:true});
        }
    }
    await page.evaluate(()=>document.documentElement.dataset.theme='light');
    await page.setViewportSize({width:390,height:844});
    await page.screenshot({path:output+'/budget-light-mobile.png',fullPage:true});
    const plain=await browser.newContext({javaScriptEnabled:false});
    const fallback=await plain.newPage();
    await fallback.goto(hub);
    assert.equal(await fallback.locator('.library-card:visible').count(),catalog.length);
    assert.equal(await fallback.locator('[data-guide-search]').isVisible(),false);
    await fallback.goto(base+'/pages/guides/mission-budget.html');
    assert.equal(await fallback.locator('[data-budget-form]').isVisible(),false);
    assert.ok(await fallback.getByRole('heading',{name:'The calculation, in plain language'}).isVisible());
    assert.ok(await fallback.locator('noscript p').isVisible());
    assert.match(await fallback.locator('noscript p').innerText(),/formulas and worked example/);
    await plain.close();
    assert.deepEqual(errors,[]);
    console.log(JSON.stringify({output,guides:catalog.length,checks:['synonym and accent search','combined category filters','empty state and reset','filtered category links','no URL query submission','text treated as text','budget example and personal costs','negative estimate','stale result hidden','invalid inputs rejected','native reset','result layout at four sizes','light theme','no-JavaScript content'],errors:0},null,2));
    await browser.close();
})().catch(error=>{console.error(error);process.exit(1)});
